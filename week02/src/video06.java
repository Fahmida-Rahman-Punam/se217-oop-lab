public class video06 {
    public static void main(String[] args) {
        int age = 32;
        if (age < 2) {
            System.out.println("infant");
        } else if (age < 10) {
            System.out.println("child");
        } else if (age < 20) {
            System.out.println("teenage");
        } else if (age < 30) {
            System.out.println("adult");
        } else {
            System.out.println("old");
        }
    }
}
